"""
The training run, start to finish, on rented cloud GPUs.

Trains a 777M-parameter (161M active per token) DeepSeek-style Mixture-of-
Experts chat model from scratch on ~6B tokens, split into two pretraining
phases on separate machines and a third stage that fine-tunes.

    PHASE 1
        python verify_cloud_run.py                   # free: validate the whole plan
        modal run cloud_run.py --stage budget         # free: print the cost ceiling
        modal run cloud_run.py --stage preflight      # ~$0.35: measure real speed first
        modal run --detach cloud_run.py --stage phase1
        # then move three files across (the run prints the exact commands)

    PHASE 2
        modal run --detach cloud_run.py --stage phase2
        modal volume get llm-v2 checkpoints/chat_final.pt ../checkpoints/chat_final.pt

Why two phases. Phase 1 pretrains the first ~52% of the schedule; phase 2
continues it and then chat-tunes. The learning rate follows ONE cosine
curve across both phases (train.py's --schedule-start / --schedule-end), so
the model anneals properly at the very end instead of decaying to zero
halfway through and being re-warmed from scratch.

What crosses the boundary: the tokenizer (~6MB), the validation tokens
(~20MB) and the phase-1 weights in bfloat16 (~1.5GB). Optimizer state is NOT
carried across -- that would be a ~9GB transfer for a small quality gain --
so phase 2 starts a fresh AdamW and re-warms over 150 steps onto the same
curve.

Spending safety, in three layers:
  * Every function has a hard timeout. worst_case_by_phase() below multiplies
    those timeouts by the provider's published prices, and an assert at import
    time refuses to load this module if any phase could exceed its budget in
    PHASE_BUDGET_USD. A bad plan fails locally, before anything runs.
  * Every command line is built by a plain function (pretrain_arguments and
    friends) so verify_cloud_run.py can check each flag against the target
    script's parser. A typo in a flag is caught for free rather than on a
    rented H100.
  * Every stage writes a marker file on the volume, so re-running after a
    failure skips work that was already paid for.
"""
