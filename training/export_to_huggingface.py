def build_repository(checkpoint_path, output_directory, repo_id, dtype, tokenizer_directory,
                     tokens_description, pretrain_data, chat_data):
    from safetensors.torch import save_file

    checkpoint = checkpoint_utils._torch_load_tolerant(checkpoint_path, map_location="cpu", mmap=True)
    raw_config = checkpoint["model_config"]
    if not isinstance(raw_config, dict):
        raw_config = dataclasses.asdict(raw_config)
    model_config = ModelConfig(**raw_config)
    # convert_legacy_expert_keys as well as normalize: a checkpoint saved before the experts
    # were stored as stacked tensors still uses one key per expert, and exporting those
    # verbatim makes transformers report them as UNEXPECTED, randomly initialize the real
    # expert weights, and answer with silence
    from model import convert_legacy_expert_keys
    state_dict = convert_legacy_expert_keys(checkpoint_utils.normalize_state_dict_keys(checkpoint["model"]))

    os.makedirs(output_directory, exist_ok=True)
    torch_dtype = {"bfloat16": torch.bfloat16, "float16": torch.float16, "float32": torch.float32}[dtype]

    # Tied weights share storage, which safetensors refuses to serialize. Drop the duplicate:
    # the wrapper re-ties it on load, exactly as GPT.__init__ does.
    if model_config.tie_input_output_embeddings:
        state_dict.pop("output_projection.weight", None)
    tensors = {f"model.{key}": value.to(torch_dtype).contiguous() for key, value in state_dict.items()}

    # the RoPE tables, computed exactly as GPT.__init__ computes them. They are float32
    # regardless of the export dtype: they are a fixed trigonometric table, rounding them to
    # bfloat16 would add positional error for no size saving worth having (256KB here).
    from model import precompute_rotary_embeddings
    rotary_cosine, rotary_sine = precompute_rotary_embeddings(
        model_config.query_key_rotary_head_dim, model_config.max_sequence_length,
        model_config.rope_theta_base, device="cpu")
    tensors["model.rotary_cosine"] = rotary_cosine.float().contiguous()
    tensors["model.rotary_sine"] = rotary_sine.float().contiguous()

    save_file(tensors, os.path.join(output_directory, "model.safetensors"), metadata={"format": "pt"})

    configuration = {
        "architectures": ["MoonfrostForCausalLM"],
        "model_type": "moonfrost",
        "architecture": raw_config,
        "auto_map": {
            "AutoConfig": "configuration_moonfrost.MoonfrostConfig",
            "AutoModelForCausalLM": "modeling_moonfrost.MoonfrostForCausalLM",
        },
        "torch_dtype": dtype,
        "use_cache": False,
        "vocab_size": model_config.vocabulary_size,
        "hidden_size": model_config.embedding_dimension,
        "num_hidden_layers": model_config.num_layers,
        "num_attention_heads": model_config.num_attention_heads,
        "max_position_embeddings": model_config.max_sequence_length,
        "tie_word_embeddings": model_config.tie_input_output_embeddings,
        "bos_token_id": 0,
        "eos_token_id": 0,
    }
    _write(output_directory, "config.json", json.dumps(configuration, indent=2))
    _write(output_directory, "configuration_moonfrost.py", CONFIGURATION_SOURCE)
    _write(output_directory, "modeling_moonfrost.py", MODELING_SOURCE)

    # the architecture itself, copied verbatim so the repo stands alone
    shutil.copy(os.path.join(HERE, "config.py"), os.path.join(output_directory, "arch_config.py"))
    architecture_source = open(os.path.join(HERE, "model.py"), encoding="utf-8").read()
    # transformers fills every tensor of a from_pretrained model out of the checkpoint file
    # rather than running GPT.__init__, so a buffer registered persistent=False is left as
    # zeros. For the RoPE tables that is silent and catastrophic -- zero cosine and sine
    # erase position entirely -- so the exported copy marks them persistent and they are
    # written into model.safetensors below.
    architecture_source = architecture_source.replace(
        'self.register_buffer("rotary_cosine", rotary_cosine, persistent=False)',
        'self.register_buffer("rotary_cosine", rotary_cosine, persistent=True)')
    architecture_source = architecture_source.replace(
        'self.register_buffer("rotary_sine", rotary_sine, persistent=False)',
        'self.register_buffer("rotary_sine", rotary_sine, persistent=True)')
    architecture_source = architecture_source.replace("from config import ModelConfig",
                                                       "from .arch_config import ModelConfig")
    _write(output_directory, "model_arch.py", architecture_source)

    shutil.copy(os.path.join(tokenizer_directory, "tokenizer.json"),
                os.path.join(output_directory, "tokenizer.json"))
    tokenizer_configuration = {
        "tokenizer_class": "PreTrainedTokenizerFast",
        "model_max_length": model_config.max_sequence_length,
        "bos_token": "<|endoftext|>",
        "eos_token": "<|endoftext|>",
        "pad_token": "<|pad|>",
        "unk_token": None,
        "clean_up_tokenization_spaces": False,
        "chat_template": CHAT_TEMPLATE,
    }
    _write(output_directory, "tokenizer_config.json", json.dumps(tokenizer_configuration, indent=2))

    best_val = float(checkpoint.get("best_val", float("nan")))
    card = MODEL_CARD.format(
        repo_name=repo_id.split("/")[-1] if repo_id else "Moonfrost",
        repo_id=repo_id or "yourname/your-model",
        total_millions=count_total_parameters(model_config) / 1e6,
        active_millions=count_active_parameters_per_token(model_config) / 1e6,
        layers=model_config.num_layers,
        dense=model_config.num_initial_dense_layers,
        moe=model_config.num_layers - model_config.num_initial_dense_layers,
        hidden=model_config.embedding_dimension,
        heads=model_config.num_attention_heads,
        kv_latent=model_config.kv_compressed_latent_dim,
        routed=model_config.num_routed_experts,
        top_k=model_config.num_activated_experts_per_token,
        shared=model_config.num_shared_experts,
        context=model_config.max_sequence_length,
        vocab=f"{model_config.vocabulary_size:,}",
        dtype=dtype,
        tokens=tokens_description,
        pretrain_data=pretrain_data,
        chat_data=chat_data,
        step=checkpoint.get("step", "unknown"),
        val_loss=f"{best_val:.4f}" if math.isfinite(best_val) else "not recorded",
    )
    _write(output_directory, "README.md", card)

    total_bytes = sum(os.path.getsize(os.path.join(output_directory, name))
                      for name in os.listdir(output_directory))
    print(f"repository written to {os.path.abspath(output_directory)} "
          f"({checkpoint_utils.format_bytes(total_bytes)})")
    for name in sorted(os.listdir(output_directory)):
        print(f"  {name:30s} {checkpoint_utils.format_bytes(os.path.getsize(os.path.join(output_directory, name)))}")
    return output_directory


def _write(directory, name, text):
    with open(os.path.join(directory, name), "w", encoding="utf-8") as handle:
        handle.write(text)


def validate(output_directory, prompt="What is bitcoin?"):
    """Loads the exported repo back through transformers the same way a
    stranger downloading it would, and generates a few tokens."""
    from transformers import AutoModelForCausalLM, AutoTokenizer

    print(f"\nloading {output_directory} back through transformers...")
    tokenizer = AutoTokenizer.from_pretrained(output_directory)
    model = AutoModelForCausalLM.from_pretrained(output_directory, trust_remote_code=True)
    model.eval()

    text = tokenizer.apply_chat_template([{"role": "user", "content": prompt}], tokenize=False)
    inputs = tokenizer(text, return_tensors="pt")
    with torch.no_grad():
        output = model.generate(**inputs, max_new_tokens=24, do_sample=False)
    reply = tokenizer.decode(output[0][inputs["input_ids"].shape[1]:], skip_special_tokens=True)
    print(f"  chat template -> {text!r}")
    print(f"  prompt: {prompt!r}")
    print(f"  reply:  {reply!r}")
    print("  the repository loads and generates correctly")


def main():
    argument_parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    argument_parser.add_argument("--ckpt", required=True)
    argument_parser.add_argument("--out", default="../hf_repo")
    argument_parser.add_argument("--tokenizer-dir", default="../tokenizer")
    argument_parser.add_argument("--repo-id", default=None, help="e.g. yourname/moonfrost-777m-chat")
    argument_parser.add_argument("--dtype", default="bfloat16", choices=["bfloat16", "float16", "float32"])
    argument_parser.add_argument("--tokens", default="an unrecorded number of tokens",
                                  help='e.g. "~4.2 billion tokens"')
    argument_parser.add_argument("--pretrain-data", default="FineWeb-Edu (educational web text)")
    argument_parser.add_argument("--chat-data", default="smol-smoltalk")
    argument_parser.add_argument("--validate", action="store_true", help="load the result back through transformers")
    argument_parser.add_argument("--push", action="store_true", help="upload to --repo-id (run `hf auth login` first)")
    argument_parser.add_argument("--private", action="store_true")
    args = argument_parser.parse_args()

    build_repository(args.ckpt, args.out, args.repo_id, args.dtype, args.tokenizer_dir,
                     args.tokens, args.pretrain_data, args.chat_data)
    if args.validate:
        validate(args.out)

    if args.push:
        if not args.repo_id:
            raise SystemExit("--push needs --repo-id, e.g. --repo-id yourname/moonfrost-777m-chat")
        from huggingface_hub import HfApi, whoami
        try:
            whoami()
        except Exception:
            raise SystemExit("not logged in. Run `hf auth login` yourself first "
                             "(create a WRITE token at https://huggingface.co/settings/tokens)")
        api = HfApi()
        api.create_repo(args.repo_id, private=args.private, exist_ok=True, repo_type="model")
        api.upload_folder(folder_path=args.out, repo_id=args.repo_id, repo_type="model")
        print(f"\nuploaded: https://huggingface.co/{args.repo_id}")


if __name__ == "__main__":
    main()
