CONFIGURATION_SOURCE = '''# Auto-generated by export_to_huggingface.py -- do not edit here.
from transformers import PretrainedConfig

from .arch_config import ModelConfig


class MoonfrostConfig(PretrainedConfig):
    # Thin PretrainedConfig wrapper around this project's ModelConfig dataclass.
    model_type = "moonfrost"

    def __init__(self, architecture=None, **kwargs):
        defaults = {field.name: field.default for field in ModelConfig.__dataclass_fields__.values()}
        self.architecture = {**defaults, **(architecture or {})}
        # mirrored so generic transformers code can read them without knowing the field names
        self.vocab_size = self.architecture["vocabulary_size"]
        self.max_position_embeddings = self.architecture["max_sequence_length"]
        self.hidden_size = self.architecture["embedding_dimension"]
        self.num_hidden_layers = self.architecture["num_layers"]
        self.num_attention_heads = self.architecture["num_attention_heads"]
        kwargs.setdefault("use_cache", False)  # the wrapper runs uncached; see the model card
        super().__init__(**kwargs)

    def to_model_config(self):
        return ModelConfig(**self.architecture)
'''

MODELING_SOURCE = '''# Auto-generated by export_to_huggingface.py -- do not edit here.
import torch
from transformers import GenerationMixin, PreTrainedModel
from transformers.modeling_outputs import CausalLMOutput

from .configuration_moonfrost import MoonfrostConfig
from .model_arch import GPT


class MoonfrostForCausalLM(PreTrainedModel, GenerationMixin):
    # DeepSeek-style Multi-head Latent Attention + Mixture-of-Experts, trained from scratch.
    # GenerationMixin is inherited explicitly: since transformers 4.50 PreTrainedModel no
    # longer provides .generate() on its own.
    config_class = MoonfrostConfig
    base_model_prefix = "model"
    main_input_name = "input_ids"
    supports_gradient_checkpointing = False
    _supports_cache_class = False
    # the input embedding and the output projection are one shared matrix, so only one copy is
    # stored in the checkpoint and the other is re-tied on load
    _tied_weights_keys = {"model.output_projection.weight": "model.token_embedding.weight"}

    def __init__(self, config):
        super().__init__(config)
        self.model = GPT(config.to_model_config())
        self.post_init()

    def get_input_embeddings(self):
        return self.model.token_embedding

    def set_input_embeddings(self, value):
        self.model.token_embedding = value

    def get_output_embeddings(self):
        return self.model.output_projection

    def set_output_embeddings(self, value):
        self.model.output_projection = value

    def _tie_weights(self):
        if self.config.architecture.get("tie_input_output_embeddings", True):
            self.model.output_projection.weight = self.model.token_embedding.weight

    def forward(self, input_ids=None, attention_mask=None, labels=None, **kwargs):
        # GPT.forward returns logits for every position when given targets, and only for the
        # final position otherwise -- which is all .generate() reads.
        logits, loss = self.model(input_ids, target_token_ids=labels)
        return CausalLMOutput(loss=loss, logits=logits)

    def prepare_inputs_for_generation(self, input_ids, **kwargs):
        context = self.config.max_position_embeddings
        return {"input_ids": input_ids[:, -context:]}

    def can_generate(self):
        return True
'''

